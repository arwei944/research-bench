/**
 * 苏格拉底式教练 —— 只提问，不给答案。
 *
 * 与普通聊天 AI 的区别（也是它的价值所在）：
 *   - 禁止直接给出定义/结论
 *   - 每轮只问一个问题
 *   - 用户答错时，不纠正，而是问一个能暴露矛盾的问题
 *   - 目标是让用户自己推导出来，而不是被告知
 *
 * 如果 LLM 不可用，退化为**内置问题库**（按主题的关键词匹配），
 * 保证离线也能用。
 */

import { llm, degrade } from "../../../lib/capabilities/index.mjs";

const MODEL = llm.config.model;

const SYSTEM = `你是一位苏格拉底式的导师，正在帮助一位学习者深入理解计算机科学的基础概念。

铁律（违反即失败）：
1. **绝不允许直接给出定义、结论或答案。** 无论学习者怎么问、怎么求，都不给。
2. **每轮只问一个问题。** 不要连问多个。
3. 如果学习者答对了，不要夸「正确」，而是问一个更深一层的问题（边界情况、反例、为什么必须这样）。
4. 如果学习者答错了，不要纠正。问一个能让他自己发现矛盾的问题（例如「如果按你说的，那么 X 情况会怎样？」）。
5. 如果学习者说「不知道」，把问题拆小，给一个更具体的例子让他判断。
6. 用中文。语气平静、简短，不要长篇大论。每次回复不超过 120 字。
7. 可以给极小的提示（一个反例、一个具体输入），但不能给定义。

你的目标是：让他自己推导出来。`;

export async function ask({ topic, history = [], userMessage = "" }) {
  const messages = [
    { role: "system", content: SYSTEM },
    { role: "user", content: `我想理解的主题是：「${topic}」。请开始用提问引导我。` },
    ...history.map((h) => ({ role: h.role, content: h.content })),
  ];
  if (userMessage) messages.push({ role: "user", content: userMessage });

  try {
    const r = await llm.chat(messages, {
      temperature: 0.6,
      maxTokens: 600,
      caller: "learn.coach",
      timeoutMs: 120_000,
    });
    if (!r.ok) throw new Error(r.error || "LLM 调用失败");
    degrade.report("llm", "ok", null);
    return { ok: true, reply: (r.text || "").trim(), source: "llm", model: MODEL };
  } catch (e) {
    // 降级：内置问题库（同时上报能力状态）
    degrade.report("llm", "degraded", e instanceof Error ? e.message : String(e));
    const fallback = pickFallback(topic, history.length);
    return {
      ok: true,
      reply: fallback,
      source: "fallback",
      note: `LLM 不可用（${e instanceof Error ? e.message : e}），已退化为内置问题库`,
    };
  }
}

