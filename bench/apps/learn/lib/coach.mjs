function pickFallback(topic, turn) {
  const chain = CHAINS.find((c) => c.match.test(topic)) ?? null;
  if (!chain) {
    return (
      `我们先从一个具体例子开始。关于「${topic}」，请你想一个你见过的、最具体的场景或代码片段——` +
      `不用抽象，越具体越好。你先说，我们再往下问。`
    );
  }
  const idx = Math.min(turn, chain.steps.length - 1);
  const step = chain.steps[idx];
  const tail = turn >= chain.steps.length ? "\n\n（这条问题链已走完。换个角度或换个主题继续。）" : "";
  return `【${chain.name} · 第 ${idx + 1}/${chain.steps.length} 问】\n\n${step}${tail}`;
}

